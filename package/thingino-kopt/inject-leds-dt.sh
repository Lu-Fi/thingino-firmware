#!/bin/sh
# Add this camera's status LEDs from its thingino.json to a 4.4 kernel device
# tree as a gpio-leds node, so /sys/class/leds/led_<colour> exists the way the
# 3.10 board file provides it (S00blink, S99led and the web UI look there).
# gpio.led_<c> is a pin number or {"pin": N, "active_low": true}; colours
# b g r w y v. Same tree handling as thingino-button's inject-button-dt.sh: a
# decompiled camera .dts has no labels, so the GPIO bank is referenced by
# phandle. A tree that already has a gpio-leds node is left alone.
#
# Usage: inject-leds-dt.sh <thingino.json> <linux-dir>
set -e

JSON="$1"
LINUX="$2"
DTSDIR="$LINUX/arch/mips/boot/dts/ingenic"
[ -f "$DTSDIR/Makefile" ] && [ -f "$LINUX/.config" ] || exit 0

fragment() {
	python3 - "$JSON" "$1" <<'PY'
import json, os, re, sys

conf, dts = sys.argv[1], sys.argv[2]
src = open(dts).read()

leds = []
if os.path.isfile(conf):
    g = json.load(open(conf)).get("gpio", {})
    for c in "bgrwyv":
        v = g.get("led_" + c)
        pin = v.get("pin") if isinstance(v, dict) else v
        low = bool(v.get("active_low")) if isinstance(v, dict) else False
        if isinstance(pin, int) and not isinstance(pin, bool) and 0 <= pin < 192:
            leds.append(("led_" + c, pin, low))


def bank(gp):
    for m in re.finditer(r"^(\t+)%s(@\S+)?\s*\{(.*?)^\1\};" % gp, src, re.M | re.S):
        p = re.search(r"^\s*phandle\s*=\s*<(\w+)>;", m.group(3), re.M)
        if "gpio-controller" in m.group(3):
            return p and p.group(1)
    return "&" + gp


print("/* Generated by thingino-kopt from thingino.json. */")
added, body = [], ""
if re.search(r"gpio-leds", src):
    leds = []
for name, pin, low in leds:
    gp = "gp" + "abcdef"[pin // 32]
    ref = bank(gp)
    if not ref:
        print("thingino-kopt: %s: %s has no phandle, %s skipped"
              % (os.path.basename(dts), gp, name), file=sys.stderr)
        continue
    body += ("\n\t\t%s {\n\t\t\tlabel = \"%s\";\n\t\t\tgpios = <%s %d %d>;\n"
             "\t\t\tdefault-state = \"off\";\n\t\t};\n"
             % (name, name, ref, pin % 32, 1 if low else 0))
    added.append("%s=gpio%d%s" % (name, pin, "/low" if low else ""))
if body:
    sys.stdout.write("\n/ {\n\tgpio-leds {\n\t\tcompatible = \"gpio-leds\";\n" + body + "\t};\n};\n")
print("thingino-kopt: %s leds: %s"
      % (os.path.basename(dts), " ".join(added) or "none"), file=sys.stderr)
PY
}

# shellcheck disable=SC2016
sed -n 's/^dtb-\$(\(CONFIG_[A-Z0-9_]*\))[[:space:]]*+=[[:space:]]*\([^[:space:]]*\)\.dtb.*/\1 \2/p' "$DTSDIR/Makefile" | while read -r opt name; do
	grep -q "^$opt=y" "$LINUX/.config" || continue
	dts="$DTSDIR/$name.dts"
	[ -f "$dts" ] || continue

	inc="$name-thingino-leds.dtsi"
	fragment "$dts" >"$DTSDIR/$inc.tmp"
	if cmp -s "$DTSDIR/$inc.tmp" "$DTSDIR/$inc"; then
		rm -f "$DTSDIR/$inc.tmp"
	else
		mv "$DTSDIR/$inc.tmp" "$DTSDIR/$inc"
	fi
	grep -q "#include \"$inc\"" "$dts" || printf '\n#include "%s"\n' "$inc" >>"$dts"
done
exit 0
